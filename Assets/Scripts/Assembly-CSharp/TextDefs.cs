	public static string AbbreviateTimestamp(double timestamp)
	{
		string text = null;
		int num = (int)Math.Floor(timestamp / 3600.0);
		int num2 = (int)Math.Ceiling(timestamp % 3600.0 / 60.0);
		if (num > 0)
		{
			text += string.Format(HOURS_ABR, num);
		}
		if (string.IsNullOrEmpty(text) || num2 > 0)
		{
			if (!string.IsNullOrEmpty(text))
			{
				text += " ";
			}
			text += string.Format(MINUTES_ABR, num2);
		}
		return text;
	}
