	public static string GetMortyStatTextForType(string type)
	{
		switch (type)
		{
		default:
			return null;
		case "Attack":
			return TextDefs.MORTY_STAT_ATTACK;
		case "Defence":
			return TextDefs.MORTY_STAT_DEFENCE;
		case "Speed":
			return TextDefs.MORTY_STAT_SPEED;
		case "Accuracy":
			return TextDefs.MORTY_STAT_ACCURACY;
		case "Evade":
			return TextDefs.MORTY_STAT_EVADE;
		}
	}

